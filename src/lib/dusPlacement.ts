export function getPlacementForNet(net: number): { rank: number; universities: string; passed: boolean } {
  if (net < 50) {
    return { rank: 0, universities: "BARAJI GEÇEMEDİNİZ", passed: false };
  }
  
  const roundedNet = Math.round(net);
  const found = DUS_PLACEMENT_DATA.find(d => d.net === roundedNet);
  if (found) {
    return { rank: found.rank, universities: found.universities, passed: true };
  }
  
  // Fallback for extremely high nets (> 120)
  if (roundedNet > 120) {
    const highest = DUS_PLACEMENT_DATA[DUS_PLACEMENT_DATA.length - 1];
    return { rank: 1, universities: highest.universities, passed: true };
  }

  // Find closest
  const sorted = [...DUS_PLACEMENT_DATA].sort((a, b) => Math.abs(a.net - roundedNet) - Math.abs(b.net - roundedNet));
  return { rank: sorted[0].rank, universities: sorted[0].universities, passed: true };
}
